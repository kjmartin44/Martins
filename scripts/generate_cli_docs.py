"""Generate the Markdown command reference from the installed CLI parsers."""

import os
from pathlib import Path
import subprocess
import sys

# argparse wraps help to the terminal width, read from $COLUMNS. Left to
# the environment, a shell that exports 120 rewrites 320 lines of the
# committed file and the CI diff reports stale docs that are not stale.
# 80 is what the committed copy was generated at, and what a piped
# process falls back to when nothing is set.
HELP_WIDTH = "80"


def main():
    root = Path(__file__).resolve().parents[1]
    sections = ["# Command reference\n\n[Documentation index](index.md)\n\n"
                "Generated by `python scripts/generate_cli_docs.py`. "
                "See [usage](usage.md) for examples and known limitations.\n"]
    # Pinned for the child only. NO_COLOR keeps argparse on Python 3.14,
    # which can colour help output, from putting escape codes in a file
    # that is committed and diffed.
    env = {**os.environ, "COLUMNS": HELP_WIDTH, "NO_COLOR": "1"}
    env.pop("FORCE_COLOR", None)
    for module in ("generoutes", "generoutes.panel",
                   "generoutes.shortlist",
                   "generoutes.explain",
                   "generoutes.audit"):
        help_text = subprocess.check_output(
            [sys.executable, "-X", "utf8", "-m", module, "--help"],
            cwd=root, text=True, encoding="utf-8", env=env)
        sections.append(f"## python -m {module}\n\n```text\n{help_text.rstrip()}\n```\n")
    # LF whatever the platform: the index holds LF, and a byte comparison
    # should not have to lean on git's line-ending normalisation.
    (root / "docs" / "cli.md").write_text(
        "\n".join(sections), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
