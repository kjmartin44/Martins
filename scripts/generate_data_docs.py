def body() -> str:
    """One section per table, from the registry."""
    out = []
    for ds in datasets.registry():
        out.append(f"### {ds.title}")
        out.append("")
        out.append(f"{ds.buys[0].upper()}{ds.buys[1:]}.")
        out.append("")

        rows = [("Supplied", ds.supply + (f" — `{ds.flag}`" if ds.flag else "")),
                ("Looks for", ", ".join(f"`{p}`" for p in ds.paths))]
        if ds.size:
            rows.append(("Size", ds.size))
        if ds.url:
            rows.append(("Source", f"<{ds.url}>"))
        rows.append(("Inventory key", f"`{ds.key}`"))

        out.append("| | |")
        out.append("| --- | --- |")
        for label, value in rows:
            out.append(f"| {label} | {value} |")
        out.append("")

        if ds.build:
            # "Built, not downloaded" is only true of a derived table.
            # BindingDB is downloaded AND then projected down, and
            # calling that "built" would send someone looking for a
            # command instead of a download.
            out.append("Built, not downloaded:"
                       if ds.supply == datasets.BUILT
                       else "Prepare it once after downloading:")
            out.append("")
            out.append("```sh")
            # Wrap the long ones the way a person would type them.
            cmd = ds.build
            parts, line = [], ""
            for token in cmd.split():
                if len(line) + len(token) > 66 and line:
                    parts.append(line + " \\")
                    line = "    " + token
                else:
                    line = f"{line} {token}".strip()
            parts.append(line)
            out.extend(parts)
            out.append("```")
            out.append("")

        if ds.without:
            out.append(f"**Without it:** {ds.without}.")
            out.append("")
        for note in ds.notes:
            out.append(note)
            out.append("")
    return "\n".join(out)


def render() -> str:
    """The prose with the registry's own counts substituted.

    A sentence like "two tables are derived" is a fact about the
    registry, and hand-counting it is how a guide starts lying about
    the thing it documents.
    """
    reg = datasets.registry()
    n_built = sum(1 for d in reg if d.supply == datasets.BUILT)
    n_prep = sum(1 for d in reg if d.build and d.supply != datasets.BUILT)
    head = HEAD.format(
        n_flag=_word(sum(1 for d in reg if d.supply == datasets.FLAG)),
        built_phrase=(f"{_word(n_built).capitalize()} table is built from "
                      f"the others" if n_built == 1 else
                      f"{_word(n_built).capitalize()} tables are built "
                      f"from the others"),
        prep_phrase=(f"{_word(n_prep)} more is" if n_prep == 1
                     else f"{_word(n_prep)} more are"),
        n_total=len(reg),
    )
    return head + body() + TAIL


_WORDS = ("no", "one", "two", "three", "four", "five", "six",
          "seven", "eight", "nine", "ten")


def _word(n: int) -> str:
    """Small numbers read better spelled out in a sentence."""
    return _WORDS[n] if n < len(_WORDS) else str(n)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true",
                   help="exit non-zero if docs/data.md is out of date, "
                        "without writing it")
    args = p.parse_args(argv)

    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; regenerate with "
                  f"python scripts/generate_data_docs.py", file=sys.stderr)
            return 1
        print("data guide already current")
        return 0

    OUT.write_text(text, encoding="utf-8", newline="\n")
    n = len(datasets.registry())
    print(f"wrote {OUT.relative_to(ROOT)} ({n} tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
